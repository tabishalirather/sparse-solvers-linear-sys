/*! \file
 *  \brief Convergence plot for iterative solvers.
 *  \author Jens-Peter Zemke
 *  \author Sabine Le Borne
 */

#ifndef CONV_PLOT_H
#define CONV_PLOT_H

/*! Structure for a convergence plot. */
struct conv_plot_s;
typedef struct conv_plot_s conv_plot_t;

/*! \brief Create a new convergence plot.
 *
 *  \return Newly created convergence plot.
 */
conv_plot_t *conv_plot_new();

/*! \brief Set a title to appear at the top of the plot.
 *
 *  An empty title will be used if not explicitly specified.
 *
 *  \param conv_plot Convergence plot.
 *  \param title Title string.
 */
void conv_plot_title(conv_plot_t *conv_plot, const char *title);

/*! \brief Set a title which can be formatted as in printf.
 *
 *  \param conv_plot Convergence plot.
 *  \param title Title string, possibly containing format specifiers.
 */
void conv_plot_titlef(conv_plot_t *conv_plot, const char *title, ...);

/*! \brief Set a label that will be used to annotate the horizontal axis.
 *
 *  A default will be used if this is not explicitly specified.
 *
 *  \param conv_plot Convergence plot.
 *  \param xlabel Label to annotate the horizontal axis.
 */
void conv_plot_xlabel(conv_plot_t *conv_plot, const char *xlabel);

/*! \brief Set a label that will be used to annotate the vertical axis.
 *
 *  A default will be used if this is not explicitly specified.
 *
 *  \param conv_plot Convergence plot.
 *  \param ylabel Label to annotate the vertical axis.
 */
void conv_plot_ylabel(conv_plot_t *conv_plot, const char *ylabel);

/*! \brief Add a line to the plot corresponding to a sequence of (absolute or
 *         relative) residual norms generated by running an iterative solver.
 *
 *  \param conv_plot Convergence plot.
 *  \param steps Number of steps that were performed by the iterative solver.
 *  \param y Array of length (steps + 1) containing the residual values to be
 *           plotted.
 */
void conv_plot_line(conv_plot_t *conv_plot, int steps, const double *y);

/*! \brief Define a name to be used as a legend entry for a previously
 *         defined line of the plot.
 *
 *  It is not necessary to set a name for every line of the plot.
 *  Specifying a name more than once is an error, i.e. a name already
 *  defined before will not be silently overwritten.
 *
 *  \param conv_plot Convergence plot.
 *  \param name Name that will appear in the legend.
 */
void conv_plot_name(conv_plot_t *conv_plot, const char *name);

/*! \brief Define a name to be used as a legend entry for a previously
 *         defined line of the plot. The given string may be formatted
 *         as in the printf family of functions.
 *
 *  \param conv_plot Convergence plot.
 *  \param name Name to appear in the legend, possibly containing format
 *              specifiers.
 */
void conv_plot_namef(conv_plot_t *conv_plot, const char *name, ...);

/*! \brief Save convergence plot to a picture file.
 *         The name of the file will consist of the given base name
 *         and a suffix depending on the picture format.
 *
 *  \param conv_plot Convergence plot.
 *  \param file_name Base name of the file to be written. A file type
 *                   extension will be appended to obtain the actual
 *                   file name.
 */
void conv_plot_save(conv_plot_t *conv_plot, const char *file_name);

/*! \brief Destroy a convergence plot.
 *
 *  \param conv_plot Convergence plot to be destroyed.
 */
void conv_plot_delete(conv_plot_t *conv_plot);

#endif
